/*******************************************************************************************
 *Brief 		:所有硬件需要初始化的函数都放在这里。
 *Param 		:无
 *Return Value:无
********************************************************************************************/
void HwInitial(void)
{
    BOARD_init();
	Set_NVIC_PriorityGroup(Group_4); 
	#ifdef ECAT_ENABLE
    	ec_timer_init();
	#endif
    SysTick_Init();  
    SRAM_Init();
	
#ifdef DM9000_ENABLE
	NOR_Init();			//nor域使能
#endif

    LED_GPIO_Config();  
    UART_Config();
    Key_IT_GPIO_Config();
    UartInit(RS232_BR);
	
#ifdef DM9000_ENABLE
	Udp_Init(0);
#endif

//	WDOG1_Init(100,50);	
	cm_backtrace_init("U503_n2r");

    /************************************************************************
    卓越系列的机器型号和室温型号要从CPLD获取，上电后CPU和CPLD分别上电，
    由于底板的复位芯片由核心板的复位信号控制，所以CPLD初始化的时间会比MCU慢。
    因此必须要确保CPU从CPLD读取PCB版本的时候，CPLD已经获取了PCB版本。
    ************************************************************************/
	delay_ms(700);	//复位芯片延时：150ms~560ms。 CPLD初始化时间：100ms。 

    m_get_hwtype(); //获取PCB版本
    CtrlModelInit(HW_MODEL);
    if((GetHwModel() == MODEL_I3201) || (GetHwModel() == MODEL_I3202) || (GetHwModel() == MODEL_I5201))
    {
        //不装室温芯片就不需要初始化
    }
    else
    {
        I2C_LM73_Init();  
	    LM73Config();	
    }
}



